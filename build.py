"""Build minified browser bundles: pip install -r requirements-build.txt first."""
from pathlib import Path
import re

from rjsmin import jsmin
from rcssmin import cssmin

ROOT = Path(__file__).resolve().parent
CORE = [
    "config", "state", "dom", "utils", "ui", "settings", "input-mode",
    "product", "api", "sales", "closest-search", "history", "print-requests",
    "capture-page", "events", "app-updates", "app",
]


def synchronize_versions():
    """sw.js APP_VERSION is the release version for every loaded app asset."""
    version = re.search(r"APP_VERSION = '(\d+)'", (ROOT / "sw.js").read_text(encoding="utf-8")).group(1)
    paths = [ROOT / name for name in [
        "index.html", "manifest.webmanifest", "sw.js",
        "js/capture-page.js", "js/zxing-scanner.js",
    ]]
    paths.extend((ROOT / "previews").glob("*.html"))
    for path in paths:
        source = path.read_text(encoding="utf-8")
        updated = re.sub(r"\?v=\d+", "?v=" + version, source)
        updated = re.sub(r'(name="webscanner-version" content=")\d+(")',
                         lambda match: match[1] + version + match[2], updated)
        if path.name == "sw.js":
            updated = re.sub(r"CACHE_NAME = 'webscanner-v\d+'", "CACHE_NAME = 'webscanner-v" + version + "'", updated)
        if updated != source:
            path.write_text(updated, encoding="utf-8")
    print(f"Release {version}: all app asset URLs and cache synchronized")


def bundle(name, modules):
    source = "\n;\n".join(
        "// " + module + ".js\n" + (ROOT / "js" / (module + ".js")).read_text(encoding="utf-8")
        for module in modules
    )
    target = ROOT / "js" / name
    target.write_text("// Generated by build.py; edit the source modules.\n" + jsmin(source) + "\n", encoding="utf-8")
    print(f"{name}: {target.stat().st_size:,} bytes")


if __name__ == "__main__":
    synchronize_versions()
    bundle("app.bundle.js", CORE)
    bundle("capture.bundle.js", ["zxing-scanner", "camera"])
    styles = ["history", "dialogs", "responsive", "redesign"]
    target = ROOT / "css" / "interface.bundle.css"
    target.write_text(
        "/* Generated by build.py. */\n" + cssmin("\n".join(
            (ROOT / "css" / (name + ".css")).read_text(encoding="utf-8")
            for name in styles
        )) + "\n", encoding="utf-8"
    )
    print(f"interface.bundle.css: {target.stat().st_size:,} bytes")
