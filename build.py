"""Build the deployable bundles using requirements-build.txt (no runtime deps)."""
from pathlib import Path
import re

import rcssmin
import rjsmin

ROOT = Path(__file__).resolve().parent
CORE = [
    "config", "state", "dom", "utils", "ui", "settings", "input-mode",
    "product", "api", "sales", "closest-search", "history", "print-requests",
    "capture-page", "events", "app-updates", "app",
]


def build():
    sw = (ROOT / "sw.js").read_text(encoding="utf-8")
    version = re.search(r"const APP_VERSION = ['\"](\d+)['\"]", sw).group(1)
    # Synchronize source references before generating bundles.
    for name in ["index.html", "manifest.webmanifest", "sw.js",
                 "js/capture-page.js", "js/zxing-scanner.js"]:
        path = ROOT / name
        content = path.read_text(encoding="utf-8")
        content = re.sub(r"\?v=\d+", f"?v={version}", content)
        content = re.sub(r"webscanner-v\d+", f"webscanner-v{version}", content)
        content = re.sub(r'(name="webscanner-version" content=")\d+',
                         lambda m: m[1] + version, content)
        path.write_text(content, encoding="utf-8")
    for target, sources in [("app", CORE), ("capture", ["zxing-scanner", "camera"])]:
        content = ";\n".join(rjsmin.jsmin((ROOT / f"js/{name}.js").read_text(encoding="utf-8"))
                              for name in sources)
        (ROOT / f"js/{target}.bundle.js").write_text(
            "// Generated by build.py; edit the source modules.\n" + content + "\n", encoding="utf-8")
    # Base/scanner/layout and essential controls are already inlined in HTML.
    css_sources = ["history.css", "dialogs.css", "responsive.css",
                   "redesign.css", "history-controls.css"]
    content = "\n".join((ROOT / "css" / name).read_text(encoding="utf-8") for name in css_sources)
    (ROOT / "css/interface.bundle.css").write_text(
        "/* Generated by build.py. */\n" + rcssmin.cssmin(content) + "\n", encoding="utf-8")
    print(f"Built Web Scanner v{version}")


if __name__ == "__main__":
    build()
