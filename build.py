"""Build the two dependency-free browser bundles: python build.py."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CORE = [
    "config", "state", "dom", "utils", "ui", "settings", "input-mode",
    "product", "api", "sales", "closest-search", "history", "print-requests",
    "capture-page", "events", "app-updates", "app",
]


def bundle(name, modules):
    source = "// Generated by build.py. Edit the source modules, then rebuild.\n"
    source += "\n;\n".join(
        "// " + module + ".js\n" + (ROOT / "js" / (module + ".js")).read_text(encoding="utf-8")
        for module in modules
    )
    target = ROOT / "js" / name
    target.write_text(source, encoding="utf-8")
    print(f"{name}: {target.stat().st_size:,} bytes")


if __name__ == "__main__":
    bundle("app.bundle.js", CORE)
    bundle("capture.bundle.js", ["zxing-scanner", "camera"])
    styles = ["history", "dialogs", "responsive", "redesign"]
    target = ROOT / "css" / "interface.bundle.css"
    target.write_text(
        "/* Generated by build.py. */\n" + "\n".join(
            (ROOT / "css" / (name + ".css")).read_text(encoding="utf-8")
            for name in styles
        ), encoding="utf-8"
    )
    print(f"interface.bundle.css: {target.stat().st_size:,} bytes")
